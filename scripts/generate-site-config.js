#!/usr/bin/env node
/**
 * Generate src/data/site-config.ts from site.yml
 *
 * Reads: _data/site.yml (or content/site.yml)
 * Writes: src/data/site-config.ts
 *
 * Extracts contact info and site metadata for use in TypeScript code
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import { parse } from 'yaml';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SITE_YAML_PATHS = [
  join(__dirname, '../_data/site.yml'),
  join(__dirname, '../content/site.yml')
];
const OUTPUT_DIR = join(__dirname, '../src/data');
const OUTPUT_PATH = join(OUTPUT_DIR, 'site-config.ts');

// Find site.yml
let siteYamlPath = null;
for (const path of SITE_YAML_PATHS) {
  if (existsSync(path)) {
    siteYamlPath = path;
    break;
  }
}

if (!siteYamlPath) {
  console.error('Error: No site.yml found in _data/ or content/');
  process.exit(1);
}

// Read and parse site.yml
const siteYaml = readFileSync(siteYamlPath, 'utf-8');
const config = parse(siteYaml);

if (!config.site) {
  console.error('Error: No "site" section found in site.yml');
  process.exit(1);
}

if (!config.contact) {
  console.error('Error: No "contact" section found in site.yml');
  process.exit(1);
}

const site = config.site;
const contact = config.contact;
const cms = config.cms || {};

// Ensure output directory exists
if (!existsSync(OUTPUT_DIR)) {
  mkdirSync(OUTPUT_DIR, { recursive: true });
}

// Extract values (with fallbacks)
const siteConfig = {
  author: site.author || '',
  email: contact.email || '',
  github: contact.github || '',
  linkedin: contact.linkedin || '',
  domain: site.domain || '',
  portfolio: contact.portfolio || '',
  // Repository in `owner/repo` form. Used as the fallback target for the
  // in-browser CMS when no explicit `cms.*` overrides are configured.
  repository: site.repository || '',
  // CMS — used by the in-browser editor when authenticated. Lets the user
  // commit posts to a repo other than the template fork (e.g. their split
  // content repo). Blank values fall back to `repository` above.
  content_repo: cms.content_repo || '',
  github_owner: cms.github_owner || '',
  content_posts_path: cms.content_posts_path || '',
  content_drafts_path: cms.content_drafts_path || '',
  // URL of the deployed Cloudflare worker that proxies Groq for the
  // editor's AI-rewrite feature. Empty disables the feature gracefully.
  worker_url: cms.worker_url || '',
};

// Generate TypeScript file
const output = `// Auto-generated from site.yml - do not edit directly
// Generated by scripts/generate-site-config.js

export const SITE_CONFIG = {
  author: ${JSON.stringify(siteConfig.author)},
  email: ${JSON.stringify(siteConfig.email)},
  github: ${JSON.stringify(siteConfig.github)},
  linkedin: ${JSON.stringify(siteConfig.linkedin)},
  domain: ${JSON.stringify(siteConfig.domain)},
  portfolio: ${JSON.stringify(siteConfig.portfolio)},
  repository: ${JSON.stringify(siteConfig.repository)},
  content_repo: ${JSON.stringify(siteConfig.content_repo)},
  github_owner: ${JSON.stringify(siteConfig.github_owner)},
  content_posts_path: ${JSON.stringify(siteConfig.content_posts_path)},
  content_drafts_path: ${JSON.stringify(siteConfig.content_drafts_path)},
  worker_url: ${JSON.stringify(siteConfig.worker_url)},
} as const;

export type SiteConfig = typeof SITE_CONFIG;
`;

writeFileSync(OUTPUT_PATH, output);
console.log(`Generated ${OUTPUT_PATH} from ${siteYamlPath}`);
